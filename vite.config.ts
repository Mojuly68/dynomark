import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

/** FNV-1a: a short, stable cache version from the list of built file names (which carry content hashes). */
function hash(text: string) {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) h = Math.imul(h ^ text.charCodeAt(i), 0x01000193);
  return (h >>> 0).toString(36);
}

/** Static files from public/ that the offline cache should hold. */
const PUBLIC_FILES = ['manifest.webmanifest', 'dynomark-icon-192.png', 'dynomark-icon-512.png', 'dynomark-apple-touch-icon.png', 'dynomark-favicon-32.png', 'dynomark-favicon.svg'];

/**
 * Writes dist/sw.js: precaches the built app so it opens offline at the gym.
 * Pages are network-first (so updates arrive on the next launch), hashed assets cache-first.
 */
function offlineWorker(): Plugin {
  return {
    name: 'dynomark-offline-worker',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const built = Object.keys(bundle).filter((f) => {
        if (f.endsWith('.map')) return false;
        // Font packages ship every script subset; only Latin is needed up front, others load on demand.
        if (f.endsWith('.woff2') && !/latin/.test(f)) return false;
        if (f.endsWith('.woff')) return false;
        return true;
      });
      const assets = [...built, ...PUBLIC_FILES].sort();
      const version = hash(assets.join('\n'));
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: worker(version, assets) });
    },
  };
}

const worker = (version: string, assets: string[]) => `// Generated by vite.config.ts. Do not edit.
const CACHE = 'dynomark-${version}';
const ASSETS = ${JSON.stringify(assets)};
const scoped = (p) => new URL(p, self.registration.scope).href;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS.map(scoped))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if ((k.startsWith('dynomark-') || k.startsWith('send-')) && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

async function page(req) {
  const cache = await caches.open(CACHE);
  try {
    const ctl = new AbortController();
    const t = setTimeout(() => ctl.abort(), 4000);
    const res = await fetch(req, { signal: ctl.signal });
    clearTimeout(t);
    if (res.ok) cache.put(scoped('index.html'), res.clone());
    return res;
  } catch {
    return (await cache.match(scoped('index.html'))) || Response.error();
  }
}

async function asset(req) {
  const hit = await caches.match(req);
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok && res.type === 'basic') (await caches.open(CACHE)).put(req, res.clone());
  return res;
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(req.mode === 'navigate' ? page(req) : asset(req));
});
`;

export default defineConfig({
  plugins: [react(), tailwindcss(), offlineWorker()],
  base: './',
  server: { port: 5180, strictPort: true },
  preview: { port: 5181, strictPort: true },
});
